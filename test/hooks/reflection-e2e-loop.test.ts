describe('E2E reflection loop: multiple afterTask completions → BM25-sorted injection (AC4)', () => {
  it('multiple reflections stored in sequence are all retrievable and sorted by relevance (AC4)', async () => {
    // GIVEN: Three different task completions for 'code' task type with varying relevance
    const reflectionResponses = [
      {
        task_type: 'code',
        task_summary: 'implement user authentication login',
        outcome: 'success' as const,
        reflection: 'User authentication was implemented using JWT with secure token storage.',
        lessons: ['Use secure JWT libraries', 'Store tokens in httpOnly cookies'],
      },
      {
        task_type: 'code',
        task_summary: 'implement code review workflow',
        outcome: 'partial' as const,
        reflection: 'Code review workflow was partially set up with some gaps in automation.',
        lessons: ['Automate code review checks', 'Set clear review criteria'],
      },
      {
        task_type: 'code',
        task_summary: 'implement database migration scripts',
        outcome: 'failure' as const,
        reflection: 'Database migration failed due to schema conflicts.',
        lessons: ['Test migrations in staging first', 'Keep migration scripts idempotent'],
      },
    ];

    // Complete three tasks in sequence
    for (const resp of reflectionResponses) {
      vi.spyOn(reflectionModule, 'generateReflection').mockResolvedValueOnce(resp);

      await handleAfterTask(db, facade, {
        session_key: `session-${resp.task_summary.slice(0, 10)}`,
        task_type: resp.task_type,
        task_summary: resp.task_summary,
        conversation_history: makeConversationHistory(),
        signals: { user_feedback: null, review_result: null, was_respawned: false, timed_out: false },
        agent_id: null,
      });

      // Wait for each async DB write
      await new Promise(r => setTimeout(r, 100));
    }

    // Verify all 3 reflections are stored
    const storedCount = db
      .prepare('SELECT COUNT(*) as cnt FROM reflections')
      .get() as { cnt: number };
    expect(storedCount.cnt).toBe(3);

    // WHEN: beforeSpawn fires for a login-related code task
    const result = await handleBeforeSpawn(db, facade, {
      task_description: 'implement login authentication system',
      task_type: 'code',
      agent_id: null,
    });

    // THEN: injection happened
    expect(result.injected_reflections.length).toBeGreaterThan(0);

    // AND: results are sorted by BM25 score descending (AC4)
    for (let i = 1; i < result.injected_reflections.length; i++) {
      expect(result.injected_reflections[i - 1].score).toBeGreaterThanOrEqual(
        result.injected_reflections[i].score,
      );
    }
  });

  it('BM25 returns most relevant reflection first when multiple stored (AC4)', async () => {
    // Insert two reflections: one highly relevant to "authentication", one about "database"
    const now = new Date().toISOString();
    facade.addReflection({
      id: 'auth-reflection',
      task_type: 'code',
      task_summary: 'implement authentication login JWT token',
      outcome: 'success',
      signals: '{}',
      reflection: 'Authentication was implemented with JWT tokens and login was secured.',
      lessons: '["Use JWT for authentication"]',
      agent_id: null,
      source_session: 's-auth',
      created_at: now,
    });
    facade.addReflection({
      id: 'db-reflection',
      task_type: 'code',
      task_summary: 'implement database schema migration',
      outcome: 'failure',
      signals: '{}',
      reflection: 'Database migration had schema conflicts causing failures.',
      lessons: '["Test migrations in staging"]',
      agent_id: null,
      source_session: 's-db',
      created_at: now,
    });

    // WHEN: beforeSpawn with login-related task description
    const result = await handleBeforeSpawn(db, facade, {
      task_description: 'implement JWT authentication token login',
      task_type: 'code',
      agent_id: null,
    });

    expect(result.injected_reflections.length).toBeGreaterThan(0);

    // BM25 ordering: auth-reflection should rank higher than db-reflection
    // because it has more keyword overlap with the query
    if (result.injected_reflections.length >= 2) {
      // Verify sort order: scores are descending
      for (let i = 1; i < result.injected_reflections.length; i++) {
        expect(result.injected_reflections[i - 1].score).toBeGreaterThanOrEqual(
          result.injected_reflections[i].score,
        );
      }
      // The most relevant reflection should be auth-related
      expect(result.injected_reflections[0].id).toBe('auth-reflection');
    } else {
      // At least one injection happened
      expect(result.injected_reflections[0].id).toBe('auth-reflection');
    }
  });

  it('afterTask writing multiple reflections then beforeSpawn respects the injection limit (AC4)', async () => {
    // GIVEN: 8 reflections stored for task_type='code' (exceeds default limit of 5)
    for (let i = 0; i < 8; i++) {
      vi.spyOn(reflectionModule, 'generateReflection').mockResolvedValueOnce({
        task_type: 'code',
        task_summary: `implement feature module ${i}`,
        outcome: 'success',
        reflection: `Feature module ${i} was implemented successfully with tests.`,
        lessons: [`Lesson from task ${i}`],
      });

      await handleAfterTask(db, facade, {
        session_key: `session-limit-${i}`,
        task_type: 'code',
        task_summary: `implement feature module ${i}`,
        conversation_history: [],
        signals: { user_feedback: 'good', review_result: null, was_respawned: false, timed_out: false },
        agent_id: null,
      });

      await new Promise(r => setTimeout(r, 50));
    }

    // Verify 8 reflections are in DB
    const cnt = db.prepare('SELECT COUNT(*) as c FROM reflections').get() as { c: number };
    expect(cnt.c).toBe(8);

    // WHEN: beforeSpawn fires (default limit = 5)
    const result = await handleBeforeSpawn(db, facade, {
      task_description: 'implement feature module code',
      task_type: 'code',
      agent_id: null,
    });

    // THEN: at most 5 injected (default reflectionInjectionLimit = 5)
    expect(result.injected_reflections.length).toBeLessThanOrEqual(5);
  });
});

