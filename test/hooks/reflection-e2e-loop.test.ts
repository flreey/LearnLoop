// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function makeTempDbPath(): string {
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'learnloop-e2e-loop-test-'));
  return path.join(tmpDir, 'test.db');
}

function makeConversationHistory(): Message[] {
  return [
    { role: 'user', content: 'Implement the feature.' },
    { role: 'assistant', content: 'The feature has been implemented.' },
  ];
}

// ---------------------------------------------------------------------------
// Test setup
// ---------------------------------------------------------------------------

let db: DB;
let tempDbPath: string;
let facade: StorageFacade;

beforeEach(() => {
  tempDbPath = makeTempDbPath();
  db = initializeDatabase(tempDbPath);
  const engine = createSearchEngine(db);
  facade = new StorageFacade(db, engine);
});

afterEach(() => {
  vi.restoreAllMocks();
  try { db.close(); } catch { /* ignore */ }
  try {
    fs.rmSync(path.dirname(tempDbPath), { recursive: true, force: true });
  } catch { /* ignore */ }
});

// ---------------------------------------------------------------------------
// AC1: afterTask-generated reflection is retrieved by beforeSpawn (full loop)
// ---------------------------------------------------------------------------

describe('E2E reflection loop: afterTask generates → beforeSpawn injects (AC1)', () => {
  it('reflection generated by afterTask is retrieved and injected by subsequent beforeSpawn (AC1)', async () => {
    // GIVEN: empty DB, LLM mock returns a known reflection
    const reflectionText = 'The code feature was implemented using TDD. Tests were written first.';
    const lessonText = 'Always write unit tests before implementation';

    vi.spyOn(reflectionModule, 'generateReflection').mockResolvedValue({
      task_type: 'code',
      task_summary: '实现代码功能',
      outcome: 'success',
      reflection: reflectionText,
      lessons: [lessonText],
    });

    // WHEN: Task A completes — afterTask hook fires with task_type='code'
    const afterTaskResult = await handleAfterTask(db, facade, {
      session_key: 'session-task-a',
      task_type: 'code',
      task_summary: '实现代码功能',
      conversation_history: makeConversationHistory(),
      signals: {
        user_feedback: 'wrong',
        review_result: null,
        was_respawned: false,
        timed_out: false,
      },
      agent_id: null,
    });

    // Wait for async DB write to complete
    await new Promise(r => setTimeout(r, 100));

    // Verify the reflection was generated and stored
    expect(afterTaskResult.reflection_id).not.toBeNull();
    const storedReflections = db
      .prepare('SELECT * FROM reflections')
      .all() as ReflectionEntry[];
    expect(storedReflections.length).toBe(1);
    expect(storedReflections[0].id).toBe(afterTaskResult.reflection_id);

    // AND: Task B is about to spawn — beforeSpawn hook fires with task_type='code'
    const beforeSpawnResult = await handleBeforeSpawn(db, facade, {
      task_description: '实现代码功能模块',
      task_type: 'code',
      agent_id: null,
    });

    // THEN: beforeSpawn retrieved and injected the reflection from Task A
    expect(beforeSpawnResult.injected_reflections.length).toBeGreaterThan(0);

    // Verify the injection contains the reflection generated by afterTask
    const injectedIds = beforeSpawnResult.injected_reflections.map(r => r.id);
    expect(injectedIds).toContain(afterTaskResult.reflection_id);
  });

  it('beforeSpawn injected_reflections includes reflection generated by afterTask (AC1)', async () => {
    // Arrange: afterTask generates a reflection
    vi.spyOn(reflectionModule, 'generateReflection').mockResolvedValue({
      task_type: 'code',
      task_summary: 'implement login feature',
      outcome: 'failure',
      reflection: 'Login implementation failed due to missing error handling.',
      lessons: ['Always handle edge cases', 'Test authentication flows'],
    });

    await handleAfterTask(db, facade, {
      session_key: 'session-a',
      task_type: 'code',
      task_summary: 'implement login feature',
      conversation_history: makeConversationHistory(),
      signals: { user_feedback: 'wrong', review_result: null, was_respawned: false, timed_out: false },
      agent_id: null,
    });

    await new Promise(r => setTimeout(r, 100));

    // Act: beforeSpawn fires for a related code task
    const result = await handleBeforeSpawn(db, facade, {
      task_description: 'implement user login',
      task_type: 'code',
      agent_id: null,
    });

    // Assert: injection happened
    expect(result.injected_reflections.length).toBeGreaterThan(0);
    expect(result.augmented_task_description.length).toBeGreaterThan('implement user login'.length);
    expect(result.augmented_task_description).toContain('implement user login');
  });
});

